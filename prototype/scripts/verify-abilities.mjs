import assert from 'node:assert/strict';
import {abilityApplies,activeAbilities,criticalWound,targetHas} from '../lib/weapon-abilities.ts';
import {resolveAttack,defaults} from '../lib/battle.ts';
assert.equal(abilityApplies('Anti-Vehicle 4+','Infantry, Psyker'),false);
assert.equal(abilityApplies('Anti-Psyker 2+','Infantry, Psyker'),true);
assert.equal(abilityApplies('Anti-non-Vehicle 4+','Infantry'),true);
assert.equal(abilityApplies('Anti-non-Vehicle 4+','Vehicle, Walker'),false);
assert.equal(abilityApplies('Sustained Hits 1: INFANTRY/BEASTS','Beasts'),true);
assert.equal(abilityApplies('Lethal Hits: VEHICLE','Infantry'),false);
assert.equal(targetHas('Anti-Psyker, Infantry','Psyker'),false);
assert.equal(criticalWound(activeAbilities(['Anti-Vehicle 4+','Anti-Psyker 2+'],'Vehicle')),4);
assert.deepEqual(activeAbilities(['Anti-Vehicle 4+'],'Infantry',{'Anti-Vehicle 4+':true}),['Anti-Vehicle 4+']);
assert.deepEqual(activeAbilities(['Torrent'],'Vehicle',{Torrent:false}),[]);
const card={name:'Fixture',faction:'Fixture',profiles:[{stats:[{label:'T',value:'10'},{label:'SV',value:'3+'}]}],keywords:'Vehicle',sections:[],invulnerableSave:''};
const a={playerId:'a',card,profile:0},d={playerId:'d',card,profile:0},player={faction:'Fixture'};
const w={name:'Fixture weapon',kind:'ranged',keywords:['Anti-Vehicle 4+','Rapid Fire 2','Melta 2','Blast'],skill:'4+',strength:'4',ap:'-1',attacks:'2',damage:'D6'};
const result=resolveAttack(a,d,w,{...defaults,halfRange:true,targetModels:10},player);
assert.equal(result.wound,'4+');assert.equal(result.attacks,'6');assert.match(result.damage,/D6\+2/);
assert.equal(resolveAttack(a,d,w,{...defaults,abilityOverrides:{'Anti-Vehicle 4+':false}},player).wound,'6+');
assert.equal(resolveAttack(a,d,{...w,keywords:['Lethal Hits: INFANTRY']},defaults,player).keywords.length,0);
assert.equal(resolveAttack(a,d,w,{...defaults,criticalHit:3},player).hit,'3+');
assert.equal(resolveAttack(a,d,{...w,strength:'8'}, {...defaults,strength:2},player).strength,10);
console.log('PASS: exact target keywords, conditional abilities, Anti/non-Anti critical thresholds and player overrides.');
