import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {validGame,readSavedGame,saveDraft} from '../lib/saved-game.ts';
const rules=JSON.parse(await readFile('data/faction-rules.json','utf8'));
const player=(team,faction)=>({id:`${team}-0`,team,name:`Player ${team}`,faction,ally:'',detachment:rules[faction].detachments[0].id});
const game={version:1,players:[player(0,'Adeptus Custodes'),player(1,'Necrons')],rules};
assert.ok(validGame(game));
assert.equal(validGame({...game,players:[game.players[0]]}),false);
assert.equal(validGame({...game,players:[game.players[0],game.players[0]]}),false);
assert.equal(validGame({...game,players:[game.players[0],{...game.players[1],team:0}]}),false);
assert.equal(validGame({...game,rules:{Necrons:{edition:11,detachments:[]}}}),false);
assert.equal(validGame({...game,players:[game.players[0],{...game.players[1],name:null}]}),false);
assert.equal(validGame({...game,players:[game.players[0],{...game.players[1],detachment:'missing'}]}),false);
assert.equal(validGame({...game,players:[game.players[0],{...game.players[1],roster:{mode:'build',text:'',entries:[null]}}]}),false);
const draft={...game,players:game.players.map(p=>({...p,faction:'',detachment:''})),rules:{}};
assert.ok(validGame(draft,false));assert.equal(validGame(draft),false);
let value=JSON.stringify(game);
Object.defineProperty(globalThis,'localStorage',{configurable:true,value:{getItem:()=>value,setItem:(_k,v)=>{value=v;}}});
assert.deepEqual(readSavedGame('test'),game);
value='{broken';assert.equal(readSavedGame('test'),null);
await saveDraft(draft);assert.deepEqual(readSavedGame('test',false),draft);
